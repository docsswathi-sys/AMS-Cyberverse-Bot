def create_event(
    name,
    description="",
    status="draft",
    start_at=None,
    end_at=None,
):
    """Create a CTF event with a validated lifecycle status."""
    name = name.strip()
    description = description.strip()
    status = status.lower().strip()

    if not name:
        raise ValueError("Event name cannot be empty.")

    if status not in {"draft", "active", "ended"}:
        raise ValueError(
            "Invalid event status. Must be draft, active, or ended."
        )

    connection = get_connection()
    try:
        cursor = connection.cursor()

        if status == "active":
            cursor.execute(
                "UPDATE events SET status='ended' WHERE status='active'"
            )

        cursor.execute(
            """
            INSERT INTO events
            (name, description, status, start_at, end_at, created_at)
            VALUES (%s, %s, %s, %s, %s, %s)
            RETURNING id
            """,
            (name, description, status, start_at, end_at, utc_now()),
        )

        event_id = cursor.fetchone()["id"]
        connection.commit()
        return event_id
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


def update_event_status(event_id, status):
    """Update an event status and enforce one active event at a time."""
    status = status.lower().strip()

    if status not in {"draft", "active", "ended"}:
        raise ValueError(
            "Invalid event status. Must be draft, active, or ended."
        )

    connection = get_connection()
    try:
        cursor = connection.cursor()
        event = cursor.execute(
            "SELECT id FROM events WHERE id=%s", (event_id,)
        ).fetchone()

        if event is None:
            return False

        if status == "active":
            cursor.execute(
                """
                UPDATE events
                SET status='ended'
                WHERE status='active' AND id != %s
                """,
                (event_id,),
            )

        cursor.execute(
            "UPDATE events SET status=%s WHERE id=%s",
            (status, event_id),
        )
        connection.commit()
        return True
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


