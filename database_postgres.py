def add_challenge(
    name,
    description,
    flag,
    points,
    category,
    event_id=None,
    difficulty="medium",
):
    if points <= 0:
        raise ValueError("Points must be greater than 0.")

    difficulty = difficulty.lower().strip()

    if difficulty not in {
        "easy",
        "medium",
        "hard",
        "expert",
    }:
        raise ValueError("Invalid difficulty.")

    if event_id is None:
        active_event = get_active_event()

        if active_event is None:
            event_id = create_event(
                "AMS Cyberverse CTF",
                "Default active CTF event.",
                "active",
            )
        else:
            event_id = active_event["id"]

    connection = get_connection()

    try:
        cursor = connection.cursor()

        cursor.execute(
            """
            INSERT INTO challenges
            (
                event_id,
                name,
                description,
                flag_hash,
                points,
                category,
                difficulty,
                is_active,
                created_at
            )
            VALUES (%s, %s, %s, %s, %s, %s, %s, 1, %s)
            RETURNING id
            """,
            (
                event_id,
                name.strip(),
                description.strip(),
                hash_flag(flag),
                points,
                category.strip(),
                difficulty,
                utc_now(),
            ),
        )

        challenge_id = cursor.fetchone()["id"]

        connection.commit()

        return challenge_id

    finally:
        connection.close()


