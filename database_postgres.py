def get_leaderboard(
    limit=10,
    event_id=None,
):
    connection = get_connection()

    try:
        cursor = connection.cursor()

        if event_id is None:
            cursor.execute(
                """
                SELECT
                    discord_id,
                    username,
                    display_name,
                    points,
                    level,
                    challenges_solved
                FROM users
                ORDER BY
                    points DESC,
                    challenges_solved DESC,
                    joined_at ASC
                LIMIT %s
                """,
                (limit,),
            )

        else:
            cursor.execute(
                """
                SELECT
                    u.discord_id,
                    u.username,
                    u.display_name,
                    COALESCE(SUM(s.points_awarded), 0) AS points,
                    u.level,
                    COUNT(s.id) AS challenges_solved
                FROM users u
                LEFT JOIN solves s
                    ON s.discord_id=u.discord_id
                    AND s.event_id=%s
                GROUP BY u.discord_id
                HAVING COALESCE(SUM(s.points_awarded), 0) > 0
                ORDER BY
                    points DESC,
                    challenges_solved DESC,
                    u.joined_at ASC
                LIMIT %s
                """,
                (
                    event_id,
                    limit,
                ),
            )

        return cursor.fetchall()

    finally:
        connection.close()


