MAX_LEVEL = 100

def get_level_from_xp(xp):
    level = 1

    while level < MAX_LEVEL:
        if xp < get_xp_required(level + 1):
            break
        level += 1

    return level


def get_xp_required(level):
    if level <= 1:
        return 0

    return int(100 * ((level - 1) ** 1.55))


